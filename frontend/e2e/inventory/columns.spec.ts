import { expect, test } from '../fixtures'
import { createConnectorGraph, uniqueName } from '../helpers/vieweditor'

test('type tabs select model columns and remember per-type column choices', async ({ page }) => {
  test.skip((page.viewportSize()?.width ?? 0) < 768, 'compact layouts show summaries instead of table columns')
  const prefix = uniqueName('Inventory Columns')
  const graph = await createConnectorGraph(page, prefix)
  await page.goto(`/inventory?q=${encodeURIComponent(prefix)}`)
  const headers = page.locator('thead')
  await page.getByTestId('inventory-tab-elements').click()
  await expect(headers.getByRole('button', { name: 'Technology', exact: true })).toBeVisible()
  await expect(headers.getByRole('button', { name: 'Connections', exact: true })).toBeVisible()
  await expect(headers.getByRole('button', { name: 'Source', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Columns', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Repository', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(headers.getByRole('button', { name: 'Repository', exact: true })).toBeVisible()
  await page.getByTestId('inventory-filter-section-kind').click()
  await page.getByTestId('inventory-kind-filter-service').click()
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await page.getByTestId('inventory-tab-views').click()
  expect(new URL(page.url()).searchParams.get('kind')).toBeNull()
  await expect(headers.getByRole('button', { name: 'Level', exact: true })).toBeVisible()
  await expect(headers.getByRole('button', { name: 'Elements', exact: true })).toBeVisible()
  await expect(headers.getByRole('button', { name: 'Connectors', exact: true })).toBeVisible()
  await expect(headers.getByRole('button', { name: 'Repository', exact: true })).toHaveCount(0)
  const view = page.locator(`[data-inventory-key="view:${graph.diagram.id}"]`)
  await expect(view.locator('td').nth(4)).toHaveText('5')
  await expect(view.locator('td').nth(5)).toHaveText('4')
  await page.getByTestId('inventory-tab-connectors').click()
  for (const name of ['Label', 'Source', 'Target', 'Relationship', 'Direction', 'View']) {
    await expect(headers.getByRole('button', { name, exact: true })).toBeVisible()
  }
  await expect(headers.getByRole('button', { name: 'Technology', exact: true })).toHaveCount(0)
  await page.getByTestId('inventory-tab-elements').click()
  await expect(headers.getByRole('button', { name: 'Repository', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Columns', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Reset columns', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(headers.getByRole('button', { name: 'Repository', exact: true })).toHaveCount(0)
  await expect(headers.getByRole('button', { name: 'Technology', exact: true })).toBeVisible()
})

test('type-specific sorts remain available in compact layouts', async ({ page }) => {
  test.skip((page.viewportSize()?.width ?? 0) >= 768, 'desktop sorts through column headers')
  const graph = await createConnectorGraph(page, uniqueName('Inventory Mobile Columns'))
  await page.goto('/inventory?type=elements')
  const sort = page.getByRole('combobox', { name: 'Sort inventory', exact: true })
  await sort.selectOption('technology:asc')
  expect(new URL(page.url()).searchParams.get('sort')).toBe('technology')
  await page.getByTestId('inventory-tab-views').click()
  await expect(sort).toHaveValue('name:asc')
  await sort.selectOption('elementCount:desc')
  expect(new URL(page.url()).searchParams.get('sort')).toBe('elementCount')
  await page.getByTestId('inventory-tab-connectors').click()
  await expect(sort).toHaveValue('name:asc')
  await sort.selectOption('direction:asc')
  await page.getByTestId('inventory-search').fill(graph.center.name)
  await expect(page.getByTestId('inventory-row').first()).toBeVisible()
  await expect(sort).toHaveValue('direction:asc')
})
