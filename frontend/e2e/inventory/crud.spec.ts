import { expect, test } from '../fixtures'
import { createConnectorGraph, uniqueName } from '../helpers/vieweditor'

// Runs against each configured layout, including mobile. All mutations use isolated fixture data.
test('creates and edits an element with the existing panel and deletes it from row actions', async ({ page }) => {
  const name = uniqueName('Inventory Created Element')
  await page.goto('/inventory')
  await page.getByTestId('inventory-new').click()
  await page.getByRole('menuitem', { name: 'New element', exact: true }).click()
  const panel = page.getByTestId('element-panel').last()
  await panel.getByTestId('element-panel-name-input').fill(name)
  await panel.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByTestId('inventory-search').fill(name)
  const row = page.getByTestId('inventory-row').filter({ hasText: name })
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: `Actions for ${name}`, exact: true }).click()
  await page.getByRole('menuitem', { name: 'Edit', exact: true }).click()
  await panel.getByTestId('element-panel-name-input').fill(`${name} Updated`)
  const save = panel.getByRole('button', { name: 'Save', exact: true })
  if (await save.count()) await save.click()
  else await page.getByTestId('inventory-search').focus()
  await expect(row).toContainText(`${name} Updated`)
  await row.getByRole('button', { name: `Actions for ${name} Updated`, exact: true }).click()
  await page.getByRole('menuitem', { name: 'Delete', exact: true }).click()
  await page.getByTestId('inventory-bulk-delete-submit').click()
  await expect(row).toHaveCount(0)
})

test('creates a view and a connector with selected endpoints', async ({ page }) => {
  const graph = await createConnectorGraph(page, uniqueName('Inventory Create Connector'))
  const viewName = uniqueName('Inventory Created View')
  const connectorName = uniqueName('Inventory Created Connector')
  await page.goto('/inventory')
  await page.getByTestId('inventory-new').click()
  await page.getByRole('menuitem', { name: 'New view', exact: true }).click()
  await page.getByRole('dialog').getByRole('textbox', { name: 'Name', exact: true }).fill(viewName)
  await page.getByRole('button', { name: 'Create view', exact: true }).click()
  await page.getByTestId('inventory-search').fill(viewName)
  await expect(page.getByTestId('inventory-row').filter({ hasText: viewName })).toBeVisible()
  await page.getByTestId('inventory-new').click()
  await page.getByRole('menuitem', { name: 'New connector', exact: true }).click()
  await page.getByLabel('Label (optional)', { exact: true }).fill(connectorName)
  await page.getByRole('dialog').getByRole('combobox', { name: 'View', exact: true }).selectOption(String(graph.diagram.id))
  await page.getByRole('dialog').getByRole('combobox', { name: 'Source', exact: true }).selectOption(String(graph.center.id))
  await page.getByRole('dialog').getByRole('combobox', { name: 'Target', exact: true }).selectOption(String(graph.outgoing.id))
  await page.getByRole('button', { name: 'Create connector', exact: true }).click()
  await page.getByTestId('inventory-search').fill(connectorName)
  await expect(page.getByTestId('inventory-row').filter({ hasText: connectorName })).toBeVisible()
})
